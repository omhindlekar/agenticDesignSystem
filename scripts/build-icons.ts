/**
 * Icon build (FR-1): copies the path data of the curated icons in
 * components/icon/icon-list.json from Material Symbols Sharp (weight 600,
 * @material-symbols/svg-600, Apache-2.0) into components/icon/icons.generated.ts.
 *
 * The package is a devDependency only: components ship just the curated paths.
 * Paths carry no fill or stroke; the Icon component draws them in currentColor.
 */
import { readFileSync, writeFileSync, statSync, existsSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const SOURCE = ['node_modules', '@material-symbols', 'svg-600', 'sharp'];

function loadList(repoRoot: string): string[] {
  const raw = JSON.parse(readFileSync(join(repoRoot, 'components', 'icon', 'icon-list.json'), 'utf8')) as { icons: string[] };
  return raw.icons;
}

/** Extracts the single path's d attribute from a Material Symbols SVG. */
function pathData(svg: string, name: string): string {
  const paths = [...svg.matchAll(/<path\b[^>]*\sd="([^"]+)"/g)].map((m) => m[1] ?? '');
  if (paths.length !== 1) throw new Error(`icon "${name}" has ${paths.length} paths; expected exactly 1`);
  if (!/viewBox="0 -960 960 960"/.test(svg)) throw new Error(`icon "${name}" has an unexpected viewBox`);
  return paths[0] ?? '';
}

export function buildIconsModule(repoRoot: string, names: string[] = loadList(repoRoot)): string {
  const dir = join(repoRoot, ...SOURCE);
  const entries = names.map((name) => {
    const file = join(dir, `${name}.svg`);
    if (!existsSync(file)) throw new Error(`unknown icon "${name}": no ${SOURCE.join('/')}/${name}.svg`);
    return [name, pathData(readFileSync(file, 'utf8'), name)] as const;
  });
  return [
    '/* Generated by scripts/build-icons.ts from components/icon/icon-list.json. Do not edit by hand. */',
    '/* Source: Material Symbols Sharp, weight 600 (@material-symbols/svg-600), Apache-2.0. */',
    '/* Run `npm run icons:build` after changing the list. */',
    '',
    `export type IconName =\n${entries.map(([n]) => `  | '${n}'`).join('\n')};`,
    '',
    `export const ICON_NAMES: readonly IconName[] = [\n${entries.map(([n]) => `  '${n}',`).join('\n')}\n];`,
    '',
    '/** viewBox of every icon. */',
    "export const ICON_VIEWBOX = '0 -960 960 960';",
    '',
    `export const ICON_PATHS: Record<IconName, string> = {\n${entries.map(([n, d]) => `  ${n}: '${d}',`).join('\n')}\n};`,
    '',
  ].join('\n');
}

const thisFile = fileURLToPath(import.meta.url);
if (process.argv[1] && statSync(process.argv[1]).ino === statSync(thisFile).ino) {
  const repoRoot = join(dirname(thisFile), '..');
  const out = join(repoRoot, 'components', 'icon', 'icons.generated.ts');
  writeFileSync(out, buildIconsModule(repoRoot), 'utf8');
  console.log(`icons:build wrote ${out}`);
}
