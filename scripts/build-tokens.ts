/**
 * Token build (FR-2, code side): compiles tokens/semantic.json + tokens/primitives.json
 * into styles/tokens.css as CSS custom properties.
 *
 * Only semantic tokens are emitted, with their primitive values resolved, so
 * components have no primitive variables available to reference.
 */
import { readFileSync, writeFileSync, mkdirSync, statSync, readdirSync, existsSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import { TokenSchema } from '../packages/schemas/src/token.js';
import type { Token } from '../packages/schemas/src/token.js';

interface TokenSources {
  primitives: unknown[];
  semantic: unknown[];
}

function loadSources(repoRoot: string): TokenSources {
  const read = (file: string): unknown[] =>
    (JSON.parse(readFileSync(join(repoRoot, 'tokens', file), 'utf8')) as { tokens: unknown[] }).tokens;
  return { primitives: read('primitives.json'), semantic: read('semantic.json') };
}

/** Returns semantic token name → resolved value, in source order. */
export function resolveSemanticTokens(repoRoot: string, sources?: TokenSources): Map<string, string> {
  const { primitives, semantic } = sources ?? loadSources(repoRoot);
  const prim = new Map<string, string>();
  for (const raw of primitives) {
    const t: Token = TokenSchema.parse(raw);
    if (t.tier !== 'primitive') throw new Error(`primitives.json contains non-primitive token ${t.name}`);
    prim.set(t.name, t.value);
  }
  const out = new Map<string, string>();
  for (const raw of semantic) {
    const t: Token = TokenSchema.parse(raw);
    if (t.tier !== 'semantic') throw new Error(`semantic.json contains non-semantic token ${t.name}`);
    const value = prim.get(t.reference);
    if (value === undefined) {
      throw new Error(`Semantic token "${t.name}" references unknown primitive "${t.reference}"`);
    }
    out.set(t.name, value);
  }
  return out;
}

/**
 * A theme or density mode: semantic overrides applied under an attribute on :root.
 * Files live in tokens/themes/*.json and use the semantic token shape, so the token
 * schema is unchanged.
 */
export interface ThemeFile {
  /** Attribute on :root that switches it on, e.g. data-theme or data-density. */
  attribute: 'data-theme' | 'data-density';
  value: string;
  /** Native colour scheme for scrollbars and form controls, for colour themes. */
  colorScheme?: 'light' | 'dark';
  /** Also apply when no data-theme is set and the OS asks for this scheme. */
  prefersColorScheme?: 'dark';
  description: string;
  tokens: Array<{ name: string; tier: 'semantic'; reference: string; description: string }>;
}

export function loadThemes(repoRoot: string): ThemeFile[] {
  const dir = join(repoRoot, 'tokens', 'themes');
  if (!existsSync(dir)) return [];
  return readdirSync(dir)
    .filter((f) => f.endsWith('.json'))
    .sort()
    .map((f) => JSON.parse(readFileSync(join(dir, f), 'utf8')) as ThemeFile);
}

/** Semantic tokens for a theme ('light' is the base): the base list with the theme's references swapped in. */
export function resolveTheme(repoRoot: string, value: string): Map<string, string> {
  const sources = loadSources(repoRoot);
  if (value === 'light') return resolveSemanticTokens(repoRoot, sources);
  const theme = loadThemes(repoRoot).find((t) => t.value === value);
  if (!theme) throw new Error(`unknown theme "${value}"`);
  const overrides = new Map(theme.tokens.map((t) => [t.name, t]));
  const semantic = (sources.semantic as Array<{ name: string }>).map((t) => overrides.get(t.name) ?? t);
  for (const name of overrides.keys()) {
    if (!(sources.semantic as Array<{ name: string }>).some((t) => t.name === name)) {
      throw new Error(`theme "${value}" overrides unknown semantic token "${name}"`);
    }
  }
  return resolveSemanticTokens(repoRoot, { primitives: sources.primitives, semantic });
}

function block(selector: string, lines: string[], indent = ''): string[] {
  return [`${indent}${selector} {`, ...lines.map((l) => `${indent}${l}`), `${indent}}`];
}

export function buildTokensCss(repoRoot: string): string {
  const resolved = resolveSemanticTokens(repoRoot);
  const out = [
    '/* Generated by scripts/build-tokens.ts from tokens/. Do not edit by hand. */',
    '/* Run `npm run tokens:build` after changing tokens/. */',
    ...block(':root', ['  color-scheme: light;', ...[...resolved].map(([name, value]) => `  --${name}: ${value};`)]),
  ];
  for (const theme of loadThemes(repoRoot)) {
    const values = theme.attribute === 'data-theme' ? resolveTheme(repoRoot, theme.value) : resolveDensity(repoRoot, theme);
    const lines = [
      ...(theme.colorScheme ? [`  color-scheme: ${theme.colorScheme};`] : []),
      ...theme.tokens.map((t) => `  --${t.name}: ${values.get(t.name)};`),
    ];
    out.push('', ...block(`:root[${theme.attribute}="${theme.value}"]`, lines));
    if (theme.prefersColorScheme) {
      out.push('', `@media (prefers-color-scheme: ${theme.prefersColorScheme}) {`, ...block(':root:not([data-theme])', lines, '  '), '}');
    }
  }
  return [...out, ''].join('\n');
}

/** Density modes only swap size tokens, so they resolve against the base theme. */
function resolveDensity(repoRoot: string, theme: ThemeFile): Map<string, string> {
  const sources = loadSources(repoRoot);
  const overrides = new Map(theme.tokens.map((t) => [t.name, t]));
  const semantic = (sources.semantic as Array<{ name: string }>).map((t) => overrides.get(t.name) ?? t);
  return resolveSemanticTokens(repoRoot, { primitives: sources.primitives, semantic });
}

const thisFile = fileURLToPath(import.meta.url);
if (process.argv[1] && statSync(process.argv[1]).ino === statSync(thisFile).ino) {
  const repoRoot = join(dirname(thisFile), '..');
  const outPath = join(repoRoot, 'styles', 'tokens.css');
  mkdirSync(dirname(outPath), { recursive: true });
  writeFileSync(outPath, buildTokensCss(repoRoot), 'utf8');
  console.log(`tokens:build wrote ${outPath}`);
}
