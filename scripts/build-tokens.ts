/**
 * Token build (FR-2, code side): compiles tokens/semantic.json + tokens/primitives.json
 * into styles/tokens.css as CSS custom properties.
 *
 * Only semantic tokens are emitted, with their primitive values resolved, so
 * components have no primitive variables available to reference.
 */
import { readFileSync, writeFileSync, mkdirSync, statSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import { TokenSchema } from '../packages/schemas/src/token.js';
import type { Token } from '../packages/schemas/src/token.js';

interface TokenSources {
  primitives: unknown[];
  semantic: unknown[];
}

function loadSources(repoRoot: string): TokenSources {
  const read = (file: string): unknown[] =>
    (JSON.parse(readFileSync(join(repoRoot, 'tokens', file), 'utf8')) as { tokens: unknown[] }).tokens;
  return { primitives: read('primitives.json'), semantic: read('semantic.json') };
}

/** Returns semantic token name → resolved value, in source order. */
export function resolveSemanticTokens(repoRoot: string, sources?: TokenSources): Map<string, string> {
  const { primitives, semantic } = sources ?? loadSources(repoRoot);
  const prim = new Map<string, string>();
  for (const raw of primitives) {
    const t: Token = TokenSchema.parse(raw);
    if (t.tier !== 'primitive') throw new Error(`primitives.json contains non-primitive token ${t.name}`);
    prim.set(t.name, t.value);
  }
  const out = new Map<string, string>();
  for (const raw of semantic) {
    const t: Token = TokenSchema.parse(raw);
    if (t.tier !== 'semantic') throw new Error(`semantic.json contains non-semantic token ${t.name}`);
    const value = prim.get(t.reference);
    if (value === undefined) {
      throw new Error(`Semantic token "${t.name}" references unknown primitive "${t.reference}"`);
    }
    out.set(t.name, value);
  }
  return out;
}

export function buildTokensCss(repoRoot: string): string {
  const resolved = resolveSemanticTokens(repoRoot);
  const lines = [...resolved].map(([name, value]) => `  --${name}: ${value};`);
  return [
    '/* Generated by scripts/build-tokens.ts from tokens/. Do not edit by hand. */',
    '/* Run `npm run tokens:build` after changing tokens/. */',
    ':root {',
    ...lines,
    '}',
    '',
  ].join('\n');
}

const thisFile = fileURLToPath(import.meta.url);
if (process.argv[1] && statSync(process.argv[1]).ino === statSync(thisFile).ino) {
  const repoRoot = join(dirname(thisFile), '..');
  const outPath = join(repoRoot, 'styles', 'tokens.css');
  mkdirSync(dirname(outPath), { recursive: true });
  writeFileSync(outPath, buildTokensCss(repoRoot), 'utf8');
  console.log(`tokens:build wrote ${outPath}`);
}
